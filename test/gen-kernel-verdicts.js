#!/usr/bin/env node
'use strict';

/*
 * Record app-kernel verdicts for grant / attest / monitor so CI can run the
 * js==kernel comparison without a coderifts-app checkout (1127 follow-up).
 *
 * Same contract as gen-toolset-kernel-verdicts.js: LIVE re-derives and fails on
 * drift; RECORDED is weaker and says so. vectors_sha256 binds the tokens.
 *
 *   node test/gen-kernel-verdicts.js            # write all three (needs app checkout)
 *   node test/gen-kernel-verdicts.js --check
 *   node test/gen-kernel-verdicts.js --family grant|attest|monitor
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const sha256 = (buf) => `sha256:${crypto.createHash('sha256').update(buf).digest('hex')}`;

function appRoot() {
  return process.env.CODERIFTS_APP_DIR || path.join(os.homedir(), 'coderifts-app');
}

function kernelPath(rel) {
  return path.join(appRoot(), 'src', 'verdict-core', rel);
}

function loadKernel(rel) {
  const p = kernelPath(rel);
  if (!fs.existsSync(p)) {
    throw new Error(
      `app kernel not found at ${p}; set CODERIFTS_APP_DIR to a coderifts-app checkout. `
      + 'This file RECORDS the kernel, so it cannot be produced without one.',
    );
  }
  // eslint-disable-next-line import/no-dynamic-require, global-require
  return { path: p, mod: require(p) };
}

function envelope(family, vectorsFile, kernelFile, verdicts) {
  return `${JSON.stringify({
    $comment: 'GENERATED by test/gen-kernel-verdicts.js. Do not hand-edit. App-kernel verdicts '
      + `for ${family} so the js==kernel comparison can run where the app checkout does not exist (CI).`,
    family,
    proves: 'The public verifier agrees with the app kernel AS OF kernel_sha256 below.',
    does_not_prove: 'Agreement with the app kernel as it stands now. Nothing here can see that repo.',
    vectors_sha256: sha256(fs.readFileSync(vectorsFile)),
    kernel_sha256: sha256(fs.readFileSync(kernelFile)),
    verdicts,
  }, null, 2)}\n`;
}

function grantVerdicts() {
  const { path: kp, mod } = loadKernel('execution-grant.js');
  const vectors = require('./grant-vectors.json');
  const cryptoMod = require('node:crypto');
  const publicKey = cryptoMod.createPublicKey(vectors.public_key_pem);
  const CLASSES = [
    'EG-VALID', 'EG-EXPIRED', 'EG-WRONG-AUDIENCE', 'EG-SCOPE-MISMATCH', 'EG-UNBOUND-DIGEST',
    'EG2-VALID', 'EG2-TRANSFERRED-EXECUTOR', 'EG2-TARGET-MISMATCH', 'EG2-AUDIENCE-MISMATCH',
    'EG2-SWAP-A', 'EG2-SWAP-B',
  ];
  const verdicts = CLASSES.map((name) => {
    const v = vectors.vectors.find((x) => x.name === name);
    if (!v) return { name, valid: null, status: `NO_VECTOR_${name}`, reason: null };
    const intended = {};
    const f = v.flags || {};
    if (f['intended-operation']) intended.operation = f['intended-operation'];
    if (f['intended-target']) {
      intended.target_id = f['intended-target'];
      intended.target_uri = f['intended-target'];
    }
    if (f['intended-audience']) intended.audience = f['intended-audience'];
    if (f['intended-executor']) intended.executor_id = f['intended-executor'];
    if (f['intended-adapter']) intended.adapter_id = f['intended-adapter'];
    if (f.after_payload != null) intended.after_payload = f.after_payload;
    if (f.receipt) intended.receipt_token = f.receipt;
    const r = mod.verifyExecutionGrant(v.token, { publicKey, intended });
    return { name, valid: r.valid, status: r.status, reason: r.reason === undefined ? null : r.reason };
  });
  const out = path.join(__dirname, 'grant-kernel-verdicts.json');
  return { out, text: envelope('grant', path.join(__dirname, 'grant-vectors.json'), kp, verdicts) };
}

function registryFor(vectors, v) {
  if (v.keys === 'empty') return vectors.empty_registry;
  if (v.keys === 'retired_registry') return vectors.retired_registry;
  return vectors.registry;
}

function attestVerdicts() {
  const { path: kp, mod } = loadKernel('execution-attestation.js');
  const vectors = require('./attest-vectors.json');
  const verdicts = vectors.vectors.map((v) => {
    const f = v.flags || {};
    const intended = {};
    if (f.grant) intended.grant = f.grant;
    if (f.receipt_digest) intended.receipt_digest = f.receipt_digest;
    const opts = { registry: registryFor(vectors, v), ...(Object.keys(intended).length ? { intended } : {}) };
    const r = mod.verifyExecutionAttestation(v.token, opts);
    return { name: v.name, valid: r.valid, status: r.status, reason: r.reason === undefined ? null : r.reason };
  });
  const out = path.join(__dirname, 'attest-kernel-verdicts.json');
  return { out, text: envelope('attest', path.join(__dirname, 'attest-vectors.json'), kp, verdicts) };
}

function monitorVerdicts() {
  const { path: kp, mod } = loadKernel('monitoring-attestation.js');
  const vectors = require('./monitor-vectors.json');
  const verdicts = vectors.vectors.map((v) => {
    const f = v.flags || {};
    const intended = {};
    if (f.decision_id) intended.decision_id = f.decision_id;
    if (f.receipt_digest) intended.receipt_digest = f.receipt_digest;
    const opts = { registry: registryFor(vectors, v), ...(Object.keys(intended).length ? { intended } : {}) };
    const r = mod.verifyMonitoringAttestation(v.token, opts);
    return { name: v.name, valid: r.valid, status: r.status, reason: r.reason === undefined ? null : r.reason };
  });
  const out = path.join(__dirname, 'monitor-kernel-verdicts.json');
  return { out, text: envelope('monitor', path.join(__dirname, 'monitor-vectors.json'), kp, verdicts) };
}

const FAMILIES = {
  grant: grantVerdicts,
  attest: attestVerdicts,
  monitor: monitorVerdicts,
};

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const famIdx = args.indexOf('--family');
  const family = famIdx >= 0 ? args[famIdx + 1] : 'all';
  const unknown = args.filter((a, i) => a !== '--check' && a !== '--family' && args[i - 1] !== '--family');
  if (unknown.length) {
    process.stderr.write(`gen-kernel-verdicts: unrecognized argument ${unknown[0]}\n`);
    process.exit(1);
  }
  const run = family === 'all' ? Object.keys(FAMILIES) : [family];
  if (run.some((f) => !FAMILIES[f])) {
    process.stderr.write(`gen-kernel-verdicts: unknown family ${family}\n`);
    process.exit(1);
  }
  let stale = false;
  for (const f of run) {
    const { out, text } = FAMILIES[f]();
    if (check) {
      const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
      if (have !== text) {
        process.stderr.write(`gen-kernel-verdicts: ${f} recorded verdicts are STALE. regenerate: node test/gen-kernel-verdicts.js --family ${f}\n`);
        stale = true;
      } else {
        process.stdout.write(`${f} kernel verdicts up to date\n`);
      }
    } else {
      fs.writeFileSync(out, text);
      process.stdout.write(`wrote ${out}\n`);
    }
  }
  if (check && stale) process.exit(1);
}

/**
 * Load a recorded fixture for CI. Throws a shaped error object { code, message } the harnesses print.
 */
function loadRecorded(family, vectorsAbsPath) {
  const fixture = path.join(__dirname, `${family}-kernel-verdicts.json`);
  if (!fs.existsSync(fixture)) {
    const err = new Error(
      `cross-check-${family}: app kernel not found and no recorded verdicts at ${fixture}; `
      + 'set CODERIFTS_APP_DIR to a coderifts-app checkout, or restore the fixture. Refusing to '
      + 'skip: this harness is the only place the public verifier is compared against the app '
      + 'kernel, and reporting a comparison that did not happen is worse than not having one.',
    );
    err.code = 'NO_RECORDED';
    throw err;
  }
  const rec = JSON.parse(fs.readFileSync(fixture, 'utf8'));
  const nowSha = sha256(fs.readFileSync(vectorsAbsPath));
  if (rec.vectors_sha256 !== nowSha) {
    const err = new Error(
      `cross-check-${family}: the recorded kernel verdicts do not describe these vectors\n`
      + `  recorded for: ${rec.vectors_sha256}\n`
      + `  vectors now : ${nowSha}\n`
      + '  regenerate them together on a machine with the app checkout:\n'
      + `    node test/gen-kernel-verdicts.js --family ${family}`,
    );
    err.code = 'STALE_VECTORS';
    throw err;
  }
  const byName = new Map((rec.verdicts || []).map((r) => [r.name, r]));
  return { rec, fixture, byName };
}

module.exports = { sha256, kernelPath, FAMILIES, loadRecorded };

if (require.main === module) main();
