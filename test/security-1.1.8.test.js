'use strict';

/*
 * 1.1.8 (2026-11-04, round 10s) — the security fixes, each measured on 1.1.7 first:
 *   T1  2026-07-k1 revoked: a receipt under it, at any ts, is valid:false — including the backdated forgery
 *       the retired state allowed (RECEIPT_FORMAT §7.1: the signer chooses ts).
 *   T2  an --intended-* flag with an empty (or no) value is a usage error, exit 2 (was GRANT_CURRENT, exit 0).
 *   T3  --as-of before ts on a v1/v2/v3 receipt is NOT_YET_VALID_AT_AS_OF (was VERIFIED_CURRENT, exit 0).
 *   T5  --help / -h print the usage and exit 0 (was exit 2).
 * Every key here is generated by the test; none is a CodeRifts key.
 */

const { describe, it, after } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { canonicalJson } = require('../verify.js');

const ROOT = path.join(__dirname, '..');
const PY = process.env.PYTHON || 'python3';
const PIN = JSON.parse(fs.readFileSync(path.join(ROOT, 'keys', 'coderifts-keys.json'), 'utf8'));
const dirs = [];
after(() => { for (const d of dirs) fs.rmSync(d, { recursive: true, force: true }); });
const tmp = () => { const d = fs.mkdtempSync(path.join(os.tmpdir(), 'rv-118-')); dirs.push(d); return d; };
const WORK = tmp();
const run = (cmd, args) => {
  const r = spawnSync(cmd, args, { cwd: WORK, encoding: 'utf8' });
  let json = null;
  try { json = JSON.parse(r.stdout.trim().split('\n').pop()); } catch (_) { /* not JSON */ }
  return { code: r.status, stdout: r.stdout, stderr: r.stderr, json };
};
const js = (file, args) => run(process.execPath, [path.join(ROOT, file), ...args]);
const py = (file, args) => run(PY, [path.join(ROOT, file), ...args]);

const receiptKey = crypto.generateKeyPairSync('ed25519');
const receiptPem = receiptKey.publicKey.export({ type: 'spki', format: 'pem' });
function receipt(v, ts, kid = 'rc-k1') {
  const b = { ...(v > 1 ? { v } : {}), kid, fp: `sha256:${'a'.repeat(64)}`, prev: 'null', caller: 'anon', ts,
    ...(v >= 2 ? { reg: 'b'.repeat(64) } : {}), ...(v >= 3 ? { ir: `sha256:${'c'.repeat(64)}` } : {}) };
  const parts = ['crchain.v1', b.kid, b.fp, b.prev, b.caller, b.ts, ...(v >= 2 ? [b.reg] : []), ...(v >= 3 ? [b.ir] : [])];
  const sig = crypto.sign(null, Buffer.from(parts.join('|'), 'utf8'), receiptKey.privateKey);
  return `${Buffer.from(JSON.stringify(b)).toString('base64url')}.${sig.toString('base64url')}`;
}

describe('T1 · 2026-07-k1 revoked: no timestamp rehabilitates it', () => {
  const entry = PIN.keys.find((k) => k.kid === '2026-07-k1');
  it('the pinned snapshot marks it revoked, with compromised_at at or before its first use', () => {
    assert.equal(entry.status, 'revoked');
    assert.equal(entry.compromised_at, '2026-07-01T00:00:00.000Z');
    assert.equal(PIN.keys.find((k) => k.kid === '2026-10-k1').status, 'active');
  });
  // The private 2026-07-k1 key is not used (and not needed): a test key stands in under the pinned entry's
  // fields, so the rule the snapshot triggers is the one exercised.
  const ring = path.join(WORK, 'ring-revoked.json');
  fs.writeFileSync(ring, JSON.stringify({ keys: [{ ...entry, public_key_pem: receiptPem }] }));
  for (const [what, ts, status] of [
    ['NEGATIVE: the backdated forgery the retired state passed (ts one minute before retired_at)', '2026-10-20T23:59:00.000Z', 'REVOKED_KEY'],
    ['a receipt dated before compromised_at', '2026-06-30T00:00:00.000Z', 'REVOKED_KEY_UNDECIDABLE'],
    ['a receipt dated after retired_at', '2026-10-22T00:00:00.000Z', 'KEY_RETIRED_AFTER_SIGNING'],
  ]) {
    it(`${what} → valid:false, exit 1, ${status}, js and py agree`, () => {
      const tok = receipt(2, ts, '2026-07-k1');
      const a = js('cli.js', [tok, '--keys', ring]);
      const b = py('verify.py', [tok, '--keys', ring]);
      assert.equal(a.code, 1);
      assert.equal(a.json.valid, false);
      assert.equal(a.json.status, status);
      assert.equal(b.code, 1);
      assert.equal(b.json.status, status);
    });
  }
});

describe('T2 · an --intended-* flag with no value checks nothing, so it is refused (exit 2)', () => {
  const key = crypto.generateKeyPairSync('ed25519');
  const pem = path.join(WORK, 'grant-pub.pem');
  fs.writeFileSync(pem, key.publicKey.export({ type: 'spki', format: 'pem' }));
  const sha = (s) => `sha256:${crypto.createHash('sha256').update(String(s)).digest('hex')}`;
  const iso = (ms) => new Date(Math.floor(ms / 1000) * 1000).toISOString().replace('.000Z', 'Z');
  const body = { v: 'cr.exec.v2', kid: 'k-118', grant_id: 'g-118', receipt_hash: sha('r'), tenant_id: 't1',
    executor_id: 'exec-a', adapter_id: 'fs', operation: 'write', target_uri: 'fs://repo/out.txt', environment: 'production',
    expected_state_token: sha(''), after_payload_hash: sha('x'), nonce_hash: sha('n'), policy_hash: sha('p'),
    audience_hash: sha('aud'), not_before: iso(Date.now() - 60e3), expires_at: iso(Date.now() + 3600e3), max_attempts: 1 };
  const grant = `${Buffer.from(JSON.stringify(body)).toString('base64url')}.${crypto.sign(null, Buffer.from(`crexec.v2|${canonicalJson(body)}`, 'utf8'), key.privateKey).toString('base64url')}`;
  const flags = ['operation', 'target', 'audience', 'executor', 'adapter', 'environment', 'scope-hash', 'after-file'];

  it('control: the grant itself is GRANT_CURRENT (exit 0)', () => {
    assert.equal(js('verify-grant.js', [grant, '--key', pem, '--json']).json.status, 'GRANT_CURRENT');
  });
  for (const f of flags) {
    it(`NEGATIVE: --intended-${f} "" → exit 2 in verify-grant.js, cli.js grant and verify_grant.py`, () => {
      for (const r of [js('verify-grant.js', [grant, '--key', pem, `--intended-${f}`, '']),
        js('cli.js', ['grant', grant, '--key', pem, `--intended-${f}`, '']),
        py('verify_grant.py', [grant, '--key', pem, `--intended-${f}`, ''])]) {
        assert.equal(r.code, 2, r.stdout + r.stderr);
        assert.match(r.stderr, new RegExp(`--intended-${f} needs a non-empty value`));
      }
    });
  }
  it('NEGATIVE: --intended-executor with no value at all → exit 2', () => {
    assert.equal(js('verify-grant.js', [grant, '--key', pem, '--intended-executor']).code, 2);
    assert.equal(py('verify_grant.py', [grant, '--key', pem, '--intended-executor']).code, 2);
  });
  it('library: a stated "" is compared, not skipped (v2) → GRANT_UNBOUND', () => {
    const G = require('../verify-grant.js');
    const ctx = { publicKey: key.publicKey, expectedKid: null };
    for (const [field, reason] of [['executor_id', 'executor_mismatch'], ['operation', 'operation_mismatch'], ['environment', 'environment_mismatch'], ['target_uri', 'target_mismatch']]) {
      const r = G.verifyExecutionGrant(grant, { ctx, intended: { [field]: '' } });
      assert.equal(r.status, 'GRANT_UNBOUND', field);
      assert.equal(r.reason, reason, field);
    }
  });
});

describe('T3 · --as-of before ts on a v1/v2/v3 receipt is NOT_YET_VALID_AT_AS_OF', () => {
  const pem = path.join(WORK, 'rc-pub.pem');
  fs.writeFileSync(pem, receiptPem);
  for (const v of [1, 2, 3]) {
    it(`NEGATIVE: v${v}, as-of one day before ts → valid:false, NOT_YET_VALID_AT_AS_OF, exit 1; at ts → valid, exit 0`, () => {
      const tok = receipt(v, '2026-10-01T12:00:00.000Z');
      const before = js('cli.js', [tok, '--key', pem, '--kid', 'rc-k1', '--as-of', '2026-09-30T12:00:00Z', '--json']);
      assert.equal(before.code, 1);
      assert.equal(before.json.valid, false);
      assert.equal(before.json.status, 'NOT_YET_VALID_AT_AS_OF');
      assert.equal(before.json.valid_at_as_of, false);
      const at = js('cli.js', [tok, '--key', pem, '--kid', 'rc-k1', '--as-of', '2026-10-01T12:00:00Z', '--json']);
      assert.equal(at.code, 0);
      assert.equal(at.json.valid, true);
    });
  }
});

describe('T5 · --help / -h exit 0; a real usage error stays exit 2', () => {
  for (const [label, r] of [
    ['cli.js --help', () => js('cli.js', ['--help'])], ['cli.js -h', () => js('cli.js', ['-h'])],
    ['cli.js grant --help', () => js('cli.js', ['grant', '--help'])], ['verify-grant.js --help', () => js('verify-grant.js', ['--help'])],
    ['verify.py --help', () => py('verify.py', ['--help'])], ['verify_grant.py --help', () => py('verify_grant.py', ['--help'])],
  ]) {
    it(`NEGATIVE: ${label} → exit 0, the usage on stdout`, () => {
      const out = r();
      assert.equal(out.code, 0, out.stderr);
      assert.match(out.stdout, /^usage: /);
    });
  }
  it('control: no arguments / an unknown flag → exit 2', () => {
    assert.equal(js('cli.js', []).code, 2);
    assert.equal(js('cli.js', ['--bogus']).code, 2);
  });
});
