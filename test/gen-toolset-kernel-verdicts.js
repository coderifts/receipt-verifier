#!/usr/bin/env node
'use strict';

/*
 * test/toolset-kernel-verdicts.json — what the APP KERNEL returned for every TS-A-* vector,
 * recorded so the comparison can still run where the app checkout does not exist.
 *
 * WHY (1127, the CI-independence half). cross-check-toolset.js compares the public
 * verify-toolset.js against coderifts-app/src/verdict-core/toolset-attestation.js. 1133 correctly
 * stopped that harness from printing a green line for a comparison it had not run. But the CI
 * workflow checks out THIS repository only (.github/workflows/verify-live-receipt.yml:23), so the
 * app kernel is never present there — and the loud failure turned a fabricated pass into a
 * permanently red job. A gate that is always red is a gate nobody reads. Neither state tested the
 * agreement in CI.
 *
 * This file is the third option: the kernel's verdicts, recorded, so CI compares the public
 * verifier against SOMETHING REAL instead of against nothing.
 *
 * WHAT IT PROVES, AND WHAT IT DOES NOT. It proves the public verifier agrees with the app kernel
 * AS OF the kernel revision recorded below. It does NOT prove agreement with the kernel as it
 * stands right now — nothing in this repository can see that repository. The live comparison
 * remains the stronger check and still runs whenever the checkout is present, and it re-derives
 * this file's contents and fails if they have gone stale. So a drifted kernel is caught on the
 * first local run, not silently carried forever.
 *
 * THE BINDING THAT MAKES IT NOT-A-LIE: vectors_sha256 pins the exact toolset-vectors.json these
 * verdicts describe. Regenerate the vectors and this file describes different tokens; the harness
 * refuses it rather than comparing verdicts to the wrong inputs.
 *
 *   node test/gen-toolset-kernel-verdicts.js            # write (requires the app checkout)
 *   node test/gen-toolset-kernel-verdicts.js --check    # exit 1 on drift
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const pub = require('../verify-toolset.js');

const VECTORS = path.join(__dirname, 'toolset-vectors.json');
const OUT = path.join(__dirname, 'toolset-kernel-verdicts.json');

function appKernelPath() {
  const root = process.env.CODERIFTS_APP_DIR || path.join(os.homedir(), 'coderifts-app');
  return path.join(root, 'src', 'verdict-core', 'toolset-attestation.js');
}

const sha256 = (buf) => `sha256:${crypto.createHash('sha256').update(buf).digest('hex')}`;

/** The opts a vector is verified under. ONE definition, shared with the harness. */
function optsFor(doc, v) {
  const opts = { registry: v.registry_override || doc.registry };
  if (v.entries_override) opts.entries = v.entries_override;
  else if (v.id === 'TS-A-VALID') opts.entries = doc.entries;
  return opts;
}

/** The signingInput probe body — identical to the harness's, defined once here. */
const PROBE_BODY = Object.freeze({
  v: pub.ATTEST_VERSION, kid: 'k', declarer: 'D', statement: pub.STATEMENTS[0],
  set_digest: 'sha256:abc', declared_at: '2026-08-25T00:00:00Z', session_id: 'S',
  receipt_digest: 'sha256:rd', framework: 'FW', framework_version: 'FV',
  guard_version: 'GV', tool_count: 3, mutating_count: 2, scope_note: 'SN',
});

function build() {
  const kernelPath = appKernelPath();
  if (!fs.existsSync(kernelPath)) {
    throw new Error(
      `app kernel not found at ${kernelPath}; set CODERIFTS_APP_DIR to a coderifts-app checkout. `
      + 'This file RECORDS the kernel, so it cannot be produced without one.',
    );
  }
  // eslint-disable-next-line import/no-dynamic-require, global-require
  const kernel = require(kernelPath);
  const doc = JSON.parse(fs.readFileSync(VECTORS, 'utf8'));

  const verdicts = doc.vectors.map((v) => {
    const r = kernel.verifyToolsetAttestation(v.token, optsFor(doc, v));
    return {
      id: v.id, valid: r.valid, status: r.status, reason: r.reason === undefined ? null : r.reason,
    };
  });

  return `${JSON.stringify({
    $comment: 'GENERATED by test/gen-toolset-kernel-verdicts.js. Do not hand-edit. These are the '
      + 'coderifts-app kernel verdicts recorded at the revision below, so the js==kernel comparison '
      + 'can run where the app checkout does not exist (CI). The LIVE comparison is stronger and '
      + 'still runs whenever the checkout is present; it also re-derives this file and fails on drift.',
    proves: 'The public verifier agrees with the app kernel AS OF kernel_sha256 below.',
    does_not_prove: 'Agreement with the app kernel as it stands now. Nothing here can see that repo.',
    // Pins the tokens these verdicts describe. Regenerate the vectors and this file is stale.
    vectors_sha256: sha256(fs.readFileSync(VECTORS)),
    kernel_sha256: sha256(fs.readFileSync(kernelPath)),
    set_digest: kernel.computeSetDigest(doc.entries).digest,
    signing_input_sha256: sha256(Buffer.from(kernel.signingInput(PROBE_BODY), 'utf8')),
    verdicts,
  }, null, 2)}\n`;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const unknown = args.filter((a) => a !== '--check');
  if (unknown.length) {
    process.stderr.write(`gen-toolset-kernel-verdicts: unrecognized argument ${unknown[0]}\n`);
    process.exit(1);
  }
  const text = build();
  if (check) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== text) {
      process.stderr.write(
        'gen-toolset-kernel-verdicts: the recorded kernel verdicts are STALE.\n'
        + '  regenerate: node test/gen-toolset-kernel-verdicts.js\n',
      );
      process.exit(1);
    }
    process.stdout.write('toolset kernel verdicts up to date\n');
    return;
  }
  fs.writeFileSync(OUT, text);
  process.stdout.write(`wrote ${OUT}\n`);
}

module.exports = { build, optsFor, PROBE_BODY, OUT, VECTORS, appKernelPath, sha256 };

if (require.main === module) main();
