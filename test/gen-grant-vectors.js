#!/usr/bin/env node
'use strict';

/*
 * Generate test/grant-vectors.json with an EPHEMERAL Ed25519 key (never the prod key).
 *
 * Reproduces cr.exec.v1 exactly (coderifts-app/docs/cr-exec-v1.md):
 *   token        = base64url(JSON(body)) '.' base64url(sig)
 *   signed bytes = 'crexec.v1|kid|receipt_digest|scope_hash|audience|operation|target_id|jti|iat|exp'
 *   signature    = raw Ed25519 over those UTF-8 bytes
 *
 * The five EG-* classes plus malformed / unknown-key / retired-key. Intended
 * bindings (audience, after-payload, receipt token) live on the vector so
 * test/run.sh can pass the matching CLI flags.
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const { computeScopeHash, receiptDigest, SIGNING_PREFIX, GRANT_VERSION } = require('../verify-grant.js');

const KID = 'eg-test-k1';
const RETIRED_KID = 'eg-retired-k0';

function b64url(buf) {
  return Buffer.from(buf).toString('base64url');
}

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
const publicPem = publicKey.export({ type: 'spki', format: 'pem' });
const retired = crypto.generateKeyPairSync('ed25519');
const retiredPem = retired.publicKey.export({ type: 'spki', format: 'pem' });

/**
 * THE RECEIPT THESE GRANTS BIND (roadmap 1125).
 *
 * This was the literal string 'receipt.token'. Every grant vector therefore bound
 * receiptDigest('receipt.token'), which resolves to NO receipt in this repository — so an adopter
 * reading our own vectors learned that the grant->receipt link does not have to hold. The bundle
 * verifier caught it: a bundle holding the real receipt and a valid grant graded INVALID, and
 * correctly, because they were about different things.
 *
 * It now binds a REAL signed receipt from test/vectors.json, so the link resolves and the vectors
 * teach the binding rather than undermine it.
 *
 * ORDERING, and it is load-bearing: vectors.json is generated by test/gen-vectors.js with its OWN
 * ephemeral key. Regenerate THAT first, then this — otherwise these grants bind a receipt token
 * that no longer exists. The two files are coupled in one direction only, and this is it.
 */
const RECEIPT_VECTORS = require('./vectors.json');
const REAL_RECEIPT = RECEIPT_VECTORS.vectors.find((v) => v.name === 'valid_v4');
if (!REAL_RECEIPT || typeof REAL_RECEIPT.token !== 'string') {
  throw new Error(
    'gen-grant-vectors: test/vectors.json has no `valid_v4` receipt to bind. Run '
    + 'node test/gen-vectors.js first — a grant bound to a receipt that does not exist is the '
    + 'defect this generator was changed to remove (1125).',
  );
}
const RECEIPT = REAL_RECEIPT.token;

/**
 * A receipt that is REAL but is NOT the one these grants bind — used by
 * EG-MISMATCH-FOREIGN-RECEIPT below, so the mismatch is between two genuine signed artifacts
 * rather than between an artifact and a string nobody ever issued.
 */
const FOREIGN_RECEIPT = (RECEIPT_VECTORS.vectors.find((v) => v.name === 'valid_v3')
  || RECEIPT_VECTORS.vectors.find((v) => v.name !== 'valid_v4')).token;
const AFTER = '{"ok":true}';
const OP = 'merge';
const TID = 'sha256:tgt';
const AUD = 'v:deadbeefdead';
const IAT = '2026-08-23T12:00:00Z';
const EXP_FUTURE = '2099-01-01T00:00:00Z';
const EXP_PAST = '2000-01-01T00:00:00Z';
const JTI = '00000000-0000-4000-8000-000000000001';

function signingInput(body) {
  return [
    SIGNING_PREFIX,
    body.kid, body.receipt_digest, body.scope_hash, body.audience,
    body.operation, body.target_id, body.jti, body.iat, body.exp,
  ].join('|');
}

function issueGrant({ kid, receipt, operation, target_id, audience, after_payload, iat, exp, jti }, signer) {
  const body = {
    v: GRANT_VERSION,
    kid,
    receipt_digest: receiptDigest(receipt),
    scope_hash: computeScopeHash({ operation, target_id, after_payload }),
    audience: audience == null ? '' : String(audience),
    operation,
    target_id,
    jti: jti || JTI,
    iat,
    exp,
  };
  const sig = crypto.sign(null, Buffer.from(signingInput(body), 'utf8'), signer);
  return `${b64url(Buffer.from(JSON.stringify(body), 'utf8'))}.${b64url(sig)}`;
}

const defaults = {
  kid: KID,
  receipt: RECEIPT,
  operation: OP,
  target_id: TID,
  audience: AUD,
  after_payload: AFTER,
  iat: IAT,
  exp: EXP_FUTURE,
};

const valid = issueGrant(defaults, privateKey);
// 1125 — binds FOREIGN_RECEIPT; verified against RECEIPT, so the digests cannot agree.
const mismatchForeign = issueGrant({ ...defaults, receipt: FOREIGN_RECEIPT }, privateKey);
const expired = issueGrant({ ...defaults, exp: EXP_PAST }, privateKey);
const retiredTok = issueGrant({ ...defaults, kid: RETIRED_KID }, retired.privateKey);

const extraField = (() => {
  const [bodyB64, sigB64] = valid.split('.');
  const body = JSON.parse(Buffer.from(bodyB64, 'base64url').toString('utf8'));
  body.cnf = { key_thumbprint: 'x' };
  return `${b64url(Buffer.from(JSON.stringify(body), 'utf8'))}.${sigB64}`;
})();

const truncated = valid.split('.')[0];
const garbage = `${b64url(Buffer.from('this is not json', 'utf8'))}.${b64url(crypto.randomBytes(64))}`;

const wrongKid = issueGrant({ ...defaults, kid: 'absent-k9' }, privateKey);

const out = {
  comment: 'EPHEMERAL key — regenerated by test/gen-grant-vectors.js; never the prod key.',
  // 1132 — see the note in test/gen-vectors.js. Asserted to resolve in this repository.
  generated_by: 'test/gen-grant-vectors.js',
  kid: KID,
  public_key_pem: publicPem,
  receipt: RECEIPT,
  after_payload: AFTER,
  operation: OP,
  target_id: TID,
  audience: AUD,
  scope_hash: computeScopeHash({ operation: OP, target_id: TID, after_payload: AFTER }),
  registry: {
    keys: [
      { kid: KID, public_key_pem: publicPem, status: 'active', valid_from: '2026-08-01T00:00:00Z', retired_at: null },
    ],
  },
  retired_registry: {
    keys: [
      {
        kid: RETIRED_KID,
        public_key_pem: retiredPem,
        status: 'retired',
        valid_from: '2026-07-01T00:00:00Z',
        retired_at: '2026-08-01T00:00:00Z',
      },
    ],
  },
  vectors: [
    {
      name: 'EG-VALID',
      token: valid,
      flags: {
        'intended-operation': OP,
        'intended-target': TID,
        'intended-audience': AUD,
        after_payload: AFTER,
        receipt: RECEIPT,
      },
      expected: { valid: true, status: 'GRANT_CURRENT' },
    },
    {
      name: 'EG-EXPIRED',
      token: expired,
      flags: {},
      expected: { valid: false, status: 'GRANT_EXPIRED', reason: 'expired' },
    },
    {
      name: 'EG-WRONG-AUDIENCE',
      token: valid,
      flags: { 'intended-audience': 'v:otherotherot' },
      expected: { valid: false, status: 'GRANT_WRONG_AUDIENCE', reason: 'audience_mismatch' },
    },
    {
      name: 'EG-SCOPE-MISMATCH',
      token: valid,
      flags: {
        'intended-operation': OP,
        'intended-target': TID,
        after_payload: AFTER + 'x',
      },
      expected: { valid: false, status: 'GRANT_SCOPE_MISMATCH', reason: 'scope_hash_mismatch' },
    },
    {
      name: 'EG-UNBOUND-DIGEST',
      token: valid,
      flags: { receipt: 'unrelated.token' },
      expected: { valid: false, status: 'GRANT_UNBOUND', reason: 'receipt_digest_mismatch' },
    },
    {
      // 1125 — the negative case, kept explicit now that the positive pair resolves.
      //
      // EG-UNBOUND-DIGEST above mismatches from the VERIFIER side: a correct grant checked against
      // a receipt it never bound. This one mismatches from the GRANT side: the token itself binds
      // a foreign — but genuinely signed — receipt, and is then checked against the real one. Same
      // status, opposite direction, and it is the shape a proof bundle sees when someone assembles
      // two valid artifacts that are not the same chain.
      name: 'EG-MISMATCH-FOREIGN-RECEIPT',
      note: 'INTENTIONALLY NON-MATCHING: this grant binds a different real receipt than the one it '
        + 'is verified against. It must never be "fixed" to match — it exists to prove the '
        + 'grant->receipt binding is actually checked.',
      token: mismatchForeign,
      // The receipt to CHECK AGAINST must be explicit. Consumers read flags.receipt and do not
      // fall back to the document-level one — test/run.sh:286 is the measured example — so an
      // empty flags block means no comparison happens at all and the vector grades GRANT_CURRENT,
      // silently asserting the opposite of what it is for. Found by run.sh, not by inspection.
      flags: { receipt: RECEIPT },
      expected: { valid: false, status: 'GRANT_UNBOUND', reason: 'receipt_digest_mismatch' },
    },
    {
      name: 'malformed-truncated',
      token: truncated,
      flags: {},
      expected: { valid: false, status: 'MALFORMED', reason: 'malformed_structure' },
    },
    {
      name: 'malformed-bad-json',
      token: garbage,
      flags: {},
      expected: { valid: false, status: 'MALFORMED', reason: 'bad_json' },
    },
    {
      name: 'malformed-unknown-field',
      token: extraField,
      flags: {},
      expected: { valid: false, status: 'MALFORMED', reason: 'unknown_field' },
    },
    {
      name: 'unknown-key',
      token: wrongKid,
      flags: {},
      expected: { valid: false, status: 'UNKNOWN_KEY', reason: 'unknown_kid' },
    },
    {
      name: 'retired-key',
      token: retiredTok,
      keys: 'retired_registry',
      flags: {},
      expected: { valid: false, status: 'UNKNOWN_KEY', reason: 'retired_kid' },
    },
  ],
};

const dest = path.join(__dirname, 'grant-vectors.json');
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
process.stdout.write(`wrote ${dest}  kid=${KID}  vectors=${out.vectors.length}\n`);
